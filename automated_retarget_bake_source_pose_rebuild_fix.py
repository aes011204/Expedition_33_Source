"""
Automated Animation Pipeline for UE 5.4+ with editor-style source pose rebuild:
1. Duplicate source AnimSequences into a temp source-fixed folder.
2. Sample evaluated pose for every raw track and every frame.
3. Rebuild the source animation from that sampled pose, while inverting the
   displayed green(Y) channel of clavicle_l.
4. Force rebuilt scales to 1,1,1 to avoid IKRig incoming-scale issues.
5. Retarget rebuilt source anims -> final character Animation folder.
6. Duplicate retargeted assets -> Animation/Create folder.
7. Bake original Root/Pelvis Y motion into the Create folder assets.

Why this variant exists:
- Direct raw-track edits did not match what the Animation Editor visually does.
- This version rewrites the source animation from evaluated pose data first,
  which is much closer to "what the editor is showing".
"""

import unreal


CHARACTERS = [
	{"name": "Lune", "folder": "/Game/Retarget/Lune", "mesh": "/Game/Retarget/Lune/Model/LuneBody", "rtg": "/Game/Retarget/Lune_RTG_AutoGenerated"},
	{"name": "Gustave", "folder": "/Game/Retarget/Gustave", "mesh": "/Game/Retarget/Gustave/Model/Gustave", "rtg": "/Game/Retarget/Gustave_RTG_AutoGenerated"},
	{"name": "Maelle", "folder": "/Game/Retarget/Maelle", "mesh": "/Game/Retarget/Maelle/Model/MaelleBody", "rtg": "/Game/Retarget/Maelle_RTG_AutoGenerated"},
]

ANIMATION_FOLDER_NAME = "Animation"
CREATE_FOLDER_NAME = "Create"
SOURCE_FIXED_FOLDER_NAME = "_SourcePoseRebuilt"
SOURCE_FIXED_SUFFIX = "_SrcPoseRebuilt"
OUTPUT_SUFFIX = "_Retargeted"

ROOT_BONE_CANDIDATES = ("root", "Root")
PELVIS_BONE_CANDIDATES = ("pelvis", "Pelvis", "RootRetarget")
CLAVICLE_L_CANDIDATES = ("clavicle_l", "Clavicle_l", "Clavicle_L", "clavicle_L")
COPY_SOURCE_PELVIS_ABSOLUTE_Y = True
DEBUG_LOG_FIRST_FRAME = True


def _log(message):
	unreal.log("[AutoAnimPipeline_SourcePoseRebuildFix] {}".format(message))


def _warn(message):
	unreal.log_warning("[AutoAnimPipeline_SourcePoseRebuildFix] {}".format(message))


def _anim_lib():
	if hasattr(unreal, "AnimationLibrary"):
		return unreal.AnimationLibrary
	if hasattr(unreal, "AnimationBlueprintLibrary"):
		return unreal.AnimationBlueprintLibrary
	raise RuntimeError("AnimationLibrary is not available.")


def _math_lib():
	for lib_name in ("MathLibrary", "KismetMathLibrary"):
		if hasattr(unreal, lib_name):
			return getattr(unreal, lib_name)
	return None


def _asset_class_name(asset_data):
	if hasattr(asset_data, "asset_class_path"):
		return str(asset_data.asset_class_path.asset_name)
	return str(asset_data.asset_class)


def _ensure_dir(path):
	if not unreal.EditorAssetLibrary.does_directory_exist(path):
		unreal.EditorAssetLibrary.make_directory(path)


def _raw_track_names(anim):
	lib = _anim_lib()
	if hasattr(lib, "get_animation_track_names"):
		return [str(name) for name in lib.get_animation_track_names(anim)]
	if hasattr(lib, "get_raw_track_names"):
		return [str(name) for name in lib.get_raw_track_names(anim)]
	return []


def _bone_exists(anim, bone_name):
	lib = _anim_lib()
	if hasattr(lib, "does_bone_name_exist"):
		try:
			return bool(lib.does_bone_name_exist(anim, bone_name))
		except Exception:
			return False
	return True


def _find_bone(anim, candidates):
	tracks = {name.lower(): name for name in _raw_track_names(anim)}
	for candidate in candidates:
		found = tracks.get(candidate.lower())
		if found:
			return found
	for candidate in candidates:
		if _bone_exists(anim, candidate):
			return candidate
	return None


def _find_track(anim, candidates):
	tracks = {name.lower(): name for name in _raw_track_names(anim)}
	for candidate in candidates:
		found = tracks.get(candidate.lower())
		if found:
			return found
	return None


def _controller(anim):
	if hasattr(anim, "get_controller"):
		controller = anim.get_controller()
		if controller:
			return controller
	try:
		controller = anim.get_editor_property("controller")
		if controller:
			return controller
	except Exception:
		pass
	if hasattr(anim, "controller"):
		controller = anim.controller
		if controller:
			return controller
	return None


def _ensure_bone_track(anim, bone_name):
	controller = _controller(anim)
	if not controller:
		return None
	if bone_name not in _raw_track_names(anim) and hasattr(controller, "add_bone_track"):
		try:
			controller.add_bone_track(bone_name, False)
		except TypeError:
			controller.add_bone_track(bone_name)
		except Exception:
			pass
	return controller


def _set_bone_track_keys(anim, bone_name, pos, rot, scale):
	controller = _ensure_bone_track(anim, bone_name)
	if controller:
		try:
			result = controller.set_bone_track_keys(bone_name, pos, rot, scale, False)
		except TypeError:
			result = controller.set_bone_track_keys(bone_name, pos, rot, scale)
		if result is False:
			raise RuntimeError("{} failed to set {} track keys.".format(anim.get_name(), bone_name))
		return True

	for lib_name in ("AnimationLibrary", "AnimationBlueprintLibrary"):
		if not hasattr(unreal, lib_name):
			continue
		lib = getattr(unreal, lib_name)
		if not hasattr(lib, "set_bone_track_keys"):
			continue
		try:
			result = lib.set_bone_track_keys(anim, bone_name, pos, rot, scale)
			if result is False:
				raise RuntimeError("{} failed to set {} track keys.".format(anim.get_name(), bone_name))
			return True
		except TypeError:
			try:
				result = lib.set_bone_track_keys(anim, bone_name, pos, rot, scale, False)
				if result is False:
					raise RuntimeError("{} failed to set {} track keys.".format(anim.get_name(), bone_name))
				return True
			except TypeError:
				pass

	raise RuntimeError("{} cannot write bone track keys.".format(anim.get_name()))


def _transform_translation(transform):
	for attr in ("translation", "location"):
		if hasattr(transform, attr):
			return getattr(transform, attr)
	if hasattr(transform, "get_translation"):
		return transform.get_translation()
	try:
		return transform.get_editor_property("translation")
	except Exception:
		pass
	try:
		return transform.get_editor_property("location")
	except Exception:
		pass
	raise RuntimeError("Could not read Transform translation from {}".format(transform))


def _transform_rotation(transform):
	if hasattr(transform, "rotation"):
		return transform.rotation
	if hasattr(transform, "get_rotation"):
		return transform.get_rotation()
	try:
		return transform.get_editor_property("rotation")
	except Exception:
		return unreal.Quat(0.0, 0.0, 0.0, 1.0)


def _transform_scale(transform):
	for attr in ("scale3d", "scale"):
		if hasattr(transform, attr):
			return getattr(transform, attr)
	if hasattr(transform, "get_scale3d"):
		return transform.get_scale3d()
	try:
		return transform.get_editor_property("scale3d")
	except Exception:
		pass
	try:
		return transform.get_editor_property("scale")
	except Exception:
		pass
	return unreal.Vector(1.0, 1.0, 1.0)


def _frame_count(anim):
	lib = _anim_lib()
	if hasattr(lib, "get_num_keys"):
		return int(lib.get_num_keys(anim))
	if hasattr(lib, "get_num_frames"):
		return int(lib.get_num_frames(anim)) + 1
	raise RuntimeError("AnimationLibrary has no frame/key count function.")


def _sample_track(anim, bone_name):
	lib = _anim_lib()
	count = _frame_count(anim)
	pos, rot, scale = [], [], []
	for frame in range(count):
		pose = lib.get_bone_pose_for_frame(anim, bone_name, frame, False)
		pos.append(_transform_translation(pose))
		rot.append(_transform_rotation(pose))
		scale.append(_transform_scale(pose))
	return {"pos": pos, "rot": rot, "scale": scale}


def _raw_position_track(anim, candidates):
	track_name = _find_track(anim, candidates)
	if not track_name:
		return None
	lib = _anim_lib()
	if not hasattr(lib, "get_raw_track_position_data"):
		return None
	try:
		values = list(lib.get_raw_track_position_data(anim, track_name))
	except Exception:
		return None
	return values if values else None


def _lerp(a, b, alpha):
	return a + (b - a) * alpha


def _resample_floats(values, target_count):
	values = list(values)
	if not values or target_count <= 0:
		return []
	if len(values) == target_count:
		return values
	if len(values) == 1 or target_count == 1:
		return [values[0] for _ in range(target_count)]
	result = []
	source_last = len(values) - 1
	target_last = target_count - 1
	for index in range(target_count):
		source_pos = (index / target_last) * source_last
		left = int(source_pos)
		right = min(left + 1, source_last)
		alpha = source_pos - left
		result.append(_lerp(values[left], values[right], alpha))
	return result


def _source_y_curves(source_anim):
	root_name = _find_bone(source_anim, ROOT_BONE_CANDIDATES)
	pelvis_name = _find_bone(source_anim, PELVIS_BONE_CANDIDATES)
	if not root_name or not pelvis_name:
		raise RuntimeError("{}: source root/pelvis bone not found".format(source_anim.get_name()))
	root_raw = _raw_position_track(source_anim, ROOT_BONE_CANDIDATES)
	pelvis_raw = _raw_position_track(source_anim, PELVIS_BONE_CANDIDATES)
	root_pos = root_raw if root_raw else _sample_track(source_anim, root_name)["pos"]
	pelvis_pos = pelvis_raw if pelvis_raw else _sample_track(source_anim, pelvis_name)["pos"]
	root_ref_y = root_pos[0].y
	root_curve = [pos.y - root_ref_y for pos in root_pos]
	pelvis_curve = [pos.y for pos in pelvis_pos]
	return root_curve, pelvis_curve


def _quat_to_rotator(quat):
	if hasattr(quat, "rotator"):
		return quat.rotator()
	math_lib = _math_lib()
	if math_lib:
		for fn_name in ("quat_rotator", "conv_quat_to_rotator"):
			if hasattr(math_lib, fn_name):
				return getattr(math_lib, fn_name)(quat)
	raise RuntimeError("Cannot convert quaternion to rotator.")


def _rotator_to_quat(rotator):
	if hasattr(rotator, "quaternion"):
		return rotator.quaternion()
	math_lib = _math_lib()
	if math_lib:
		for fn_name in ("rotator_quat", "conv_rotator_to_quat"):
			if hasattr(math_lib, fn_name):
				return getattr(math_lib, fn_name)(rotator)
	raise RuntimeError("Cannot convert rotator to quaternion.")


def _invert_editor_green_channel(rotator):
	pitch = getattr(rotator, "pitch", 0.0)
	yaw = getattr(rotator, "yaw", 0.0)
	roll = getattr(rotator, "roll", 0.0)
	return unreal.Rotator(pitch=(-1.0 * pitch), yaw=yaw, roll=roll)


def _rebuild_source_anim_from_sampled_pose(anim):
	track_names = _raw_track_names(anim)
	if not track_names:
		raise RuntimeError("{}: no raw tracks found.".format(anim.get_name()))

	clavicle_name = _find_track(anim, CLAVICLE_L_CANDIDATES)
	if not clavicle_name:
		raise RuntimeError("{}: clavicle_l track not found.".format(anim.get_name()))

	sampled_tracks = {}
	_log("{}: sampling evaluated pose for {} tracks...".format(anim.get_name(), len(track_names)))
	for track_name in track_names:
		sampled_tracks[track_name] = _sample_track(anim, track_name)

	clavicle_track = sampled_tracks[clavicle_name]
	new_clavicle_rot = []
	for index, quat in enumerate(clavicle_track["rot"]):
		rotator = _quat_to_rotator(quat)
		new_rotator = _invert_editor_green_channel(rotator)
		if DEBUG_LOG_FIRST_FRAME and index == 0:
			_log(
				"{}: {} frame0 display XYZ before=({:.3f}, {:.3f}, {:.3f}) after=({:.3f}, {:.3f}, {:.3f})".format(
					anim.get_name(),
					clavicle_name,
					getattr(rotator, "roll", 0.0),
					getattr(rotator, "pitch", 0.0),
					getattr(rotator, "yaw", 0.0),
					getattr(new_rotator, "roll", 0.0),
					getattr(new_rotator, "pitch", 0.0),
					getattr(new_rotator, "yaw", 0.0),
				)
			)
		new_clavicle_rot.append(_rotator_to_quat(new_rotator))
	clavicle_track["rot"] = new_clavicle_rot

	controller = _controller(anim)
	if controller and hasattr(controller, "open_bracket"):
		controller.open_bracket("Rebuild source anim from evaluated pose with clavicle fix", False)
	try:
		for track_name in track_names:
			track = sampled_tracks[track_name]
			one_scale = [unreal.Vector(1.0, 1.0, 1.0) for _ in range(len(track["pos"]))]
			_set_bone_track_keys(anim, track_name, track["pos"], track["rot"], one_scale)
	finally:
		if controller and hasattr(controller, "close_bracket"):
			controller.close_bracket(False)

	try:
		anim.mark_package_dirty()
	except Exception:
		pass
	try:
		anim.post_edit_change()
	except Exception:
		pass
	unreal.EditorAssetLibrary.save_loaded_asset(anim)

	verify_clavicle = _sample_track(anim, clavicle_name)
	verify_rotator = _quat_to_rotator(verify_clavicle["rot"][0])
	if DEBUG_LOG_FIRST_FRAME:
		_log(
			"{}: {} frame0 verified XYZ=({:.3f}, {:.3f}, {:.3f})".format(
				anim.get_name(),
				clavicle_name,
				getattr(verify_rotator, "roll", 0.0),
				getattr(verify_rotator, "pitch", 0.0),
				getattr(verify_rotator, "yaw", 0.0),
			)
		)
	return True


def execute_bake(target_anim, source_root_y, source_pelvis_y):
	root_name = _find_bone(target_anim, ROOT_BONE_CANDIDATES)
	pelvis_name = _find_bone(target_anim, PELVIS_BONE_CANDIDATES)
	if not root_name or not pelvis_name:
		_warn("{}: root/pelvis bone not found".format(target_anim.get_name()))
		return False
	root = _sample_track(target_anim, root_name)
	pelvis = _sample_track(target_anim, pelvis_name)
	root_ref = root["pos"][0]
	pelvis_ref = pelvis["pos"][0]
	root_y_curve = _resample_floats(source_root_y, len(root["pos"]))
	pelvis_y_curve = _resample_floats(source_pelvis_y, len(root["pos"]))
	new_root_pos, new_pelvis_pos = [], []
	for index in range(len(root["pos"])):
		root_delta_y = root_y_curve[index]
		new_root_pos.append(unreal.Vector(root_ref.x, root_ref.y + root_delta_y, root_ref.z))
		if COPY_SOURCE_PELVIS_ABSOLUTE_Y:
			pelvis_y = pelvis_y_curve[index]
		else:
			pelvis_y = pelvis_ref.y + (pelvis_y_curve[index] - pelvis_y_curve[0])
		new_pelvis_pos.append(unreal.Vector(pelvis["pos"][index].x, pelvis_y, pelvis["pos"][index].z))
	controller = _controller(target_anim)
	if controller and hasattr(controller, "open_bracket"):
		controller.open_bracket("Bake evaluated pelvis Y to root Y", False)
	try:
		_set_bone_track_keys(target_anim, root_name, new_root_pos, root["rot"], root["scale"])
		_set_bone_track_keys(target_anim, pelvis_name, new_pelvis_pos, pelvis["rot"], pelvis["scale"])
	finally:
		if controller and hasattr(controller, "close_bracket"):
			controller.close_bracket(False)
	try:
		target_anim.set_editor_property("enable_root_motion", False)
	except Exception:
		pass
	unreal.EditorAssetLibrary.save_loaded_asset(target_anim)
	_log("{}: Baked successfully. Root Y delta: {:.3f}".format(target_anim.get_name(), new_root_pos[-1].y - new_root_pos[0].y))
	return True


def _collect_source_anims(folder):
	all_paths = unreal.EditorAssetLibrary.list_assets(folder, recursive=False)
	anims_to_rtg = []
	src_paths = {}
	for path in all_paths:
		ad = unreal.EditorAssetLibrary.find_asset_data(path)
		if _asset_class_name(ad) == "AnimSequence":
			anims_to_rtg.append(ad)
			src_paths[str(ad.asset_name)] = path
	return anims_to_rtg, src_paths


def _collect_anim_asset_data(folder):
	all_paths = unreal.EditorAssetLibrary.list_assets(folder, recursive=False)
	results = []
	for path in all_paths:
		ad = unreal.EditorAssetLibrary.find_asset_data(path)
		if _asset_class_name(ad) == "AnimSequence":
			results.append(ad)
	return results


def _match_source_path(clean_name, src_paths):
	if clean_name in src_paths:
		return src_paths[clean_name]
	for src_name, src_path in src_paths.items():
		if src_name in clean_name:
			return src_path
	return None


def main():
	for char in CHARACTERS:
		_log("=== Processing Character: {} ===".format(char["name"]))
		rtg_asset = unreal.EditorAssetLibrary.load_asset(char["rtg"])
		tgt_mesh = unreal.EditorAssetLibrary.load_asset(char["mesh"])
		if not rtg_asset or not tgt_mesh:
			_warn("Missing RTG or Target Mesh for {}".format(char["name"]))
			continue

		src_mesh = None
		for prop_name in ("source_skeletal_mesh", "source_mesh", "source_mesh_asset"):
			try:
				src_mesh = rtg_asset.get_editor_property(prop_name)
				if src_mesh:
					break
			except Exception:
				continue
		if not src_mesh:
			src_mesh = tgt_mesh

		source_anims, src_paths_dict = _collect_source_anims(char["folder"])
		if not source_anims:
			_log("No AnimSequences found in {}".format(char["folder"]))
			continue

		anim_dir = "{}/{}".format(char["folder"], ANIMATION_FOLDER_NAME)
		create_dir = "{}/{}".format(anim_dir, CREATE_FOLDER_NAME)
		source_fixed_dir = "{}/{}".format(anim_dir, SOURCE_FIXED_FOLDER_NAME)
		for directory in (anim_dir, create_dir, source_fixed_dir):
			_ensure_dir(directory)

		_log("1. Duplicating source anims into source-fixed folder and rebuilding them from evaluated pose...")
		for source_anim_ad in source_anims:
			src_name = str(source_anim_ad.asset_name)
			src_path = src_paths_dict[src_name]
			fixed_name = "{}{}".format(src_name, SOURCE_FIXED_SUFFIX)
			fixed_path = "{}/{}".format(source_fixed_dir, fixed_name)
			try:
				if unreal.EditorAssetLibrary.does_asset_exist(fixed_path):
					unreal.EditorAssetLibrary.delete_asset(fixed_path)
				unreal.EditorAssetLibrary.duplicate_asset(src_path, fixed_path)
				fixed_anim = unreal.EditorAssetLibrary.load_asset(fixed_path)
				if not fixed_anim:
					raise RuntimeError("Failed to load duplicated source anim {}".format(fixed_path))
				_rebuild_source_anim_from_sampled_pose(fixed_anim)
			except Exception as fix_ex:
				_warn("Source pose rebuild failed for {}: {}".format(src_name, str(fix_ex)))

		try:
			unreal.EditorLoadingAndSavingUtils.save_dirty_packages(True, True)
		except Exception:
			pass
		unreal.SystemLibrary.collect_garbage()

		fixed_source_anims = _collect_anim_asset_data(source_fixed_dir)
		if not fixed_source_anims:
			_warn("No rebuilt source anims found for {}".format(char["name"]))
			continue

		try:
			_log("2. Retargeting {} rebuilt source animations...".format(len(fixed_source_anims)))
			results = unreal.IKRetargetBatchOperation.duplicate_and_retarget(
				fixed_source_anims, src_mesh, tgt_mesh, rtg_asset, "", "", "", OUTPUT_SUFFIX, True
			)

			if results:
				_log("3. Moving to Animation folder, duplicating to Create folder, and baking...")
				for res in results:
					raw_retargeted_path = str(res.package_name)
					asset_name = str(res.asset_name)
					anim_path = "{}/{}".format(anim_dir, asset_name)
					try:
						if raw_retargeted_path != anim_path:
							if unreal.EditorAssetLibrary.does_asset_exist(anim_path):
								unreal.EditorAssetLibrary.delete_asset(anim_path)
							unreal.EditorAssetLibrary.rename_asset(raw_retargeted_path, anim_path)
					except Exception as move_ex:
						_warn("Could not move {} to Animation folder: {}".format(asset_name, str(move_ex)))
						continue

					try:
						clean_name = asset_name[:-len(OUTPUT_SUFFIX)] if asset_name.endswith(OUTPUT_SUFFIX) else asset_name
						if clean_name.endswith(SOURCE_FIXED_SUFFIX):
							clean_name = clean_name[:-len(SOURCE_FIXED_SUFFIX)]
						matched_src_path = _match_source_path(clean_name, src_paths_dict)
						if not matched_src_path:
							_warn("Skipping {}: no matching source found for '{}'.".format(asset_name, clean_name))
							continue
						source_anim = unreal.EditorAssetLibrary.load_asset(matched_src_path)
						if not source_anim:
							_warn("Skipping {}: failed to load source anim at {}".format(asset_name, matched_src_path))
							continue
						source_root_y, source_pelvis_y = _source_y_curves(source_anim)
						create_path = "{}/{}".format(create_dir, asset_name)
						if unreal.EditorAssetLibrary.does_asset_exist(create_path):
							unreal.EditorAssetLibrary.delete_asset(create_path)
						unreal.EditorAssetLibrary.duplicate_asset(anim_path, create_path)
						baked_anim = unreal.EditorAssetLibrary.load_asset(create_path)
						if baked_anim:
							execute_bake(baked_anim, source_root_y, source_pelvis_y)
					except Exception as bake_ex:
						_warn("Skipped baking for {}: {}".format(asset_name, str(bake_ex)))
		except Exception as exc:
			_warn("Failed retargeting batch operation for {}: {}".format(char["name"], str(exc)))

	unreal.SystemLibrary.collect_garbage()
	_log("=== Pipeline Complete ===")


if __name__ == "__main__":
	main()
