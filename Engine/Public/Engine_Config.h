#pragma once

// Debug build에서 DX11 debug layer를 켤지 결정한다.
// D3D11 Live Object ref Count Checker 작동 여부에 영향을 미친다.
#ifndef ENGINE_ENABLE_DX11_DEBUG_LAYER
#define ENGINE_ENABLE_DX11_DEBUG_LAYER 1
#endif

// 프로파일 창의 수집 레벨을 설정
#define ENGINE_PROFILE_LEVEL_OFF 0
#define ENGINE_PROFILE_LEVEL_BASIC 1
#define ENGINE_PROFILE_LEVEL_DETAIL 2

// Debug는 큰 단위 profile을 기본으로 켜고, Release는 성능 오염을 피하기 위해 기본으로 끈다.
#ifndef ENGINE_PROFILE_LEVEL
#ifdef _DEBUG
#define ENGINE_PROFILE_LEVEL ENGINE_PROFILE_LEVEL_BASIC
#else
#define ENGINE_PROFILE_LEVEL ENGINE_PROFILE_LEVEL_OFF
#endif
#endif

#define ENGINE_PROFILE_SAMPLE_EVERY_FRAME 0.0f

// 프로파일 레벨에 따라 수집 간격 설정
#if ENGINE_PROFILE_LEVEL >= ENGINE_PROFILE_LEVEL_DETAIL
#define ENGINE_PROFILE_TIMING_SAMPLE_INTERVAL_SEC ENGINE_PROFILE_SAMPLE_EVERY_FRAME
#define ENGINE_PROFILE_PROCESS_MEMORY_SAMPLE_INTERVAL_SEC ENGINE_PROFILE_SAMPLE_EVERY_FRAME
#define ENGINE_PROFILE_RESOURCE_MEMORY_SAMPLE_INTERVAL_SEC 0.25f
#define ENGINE_RUNTIME_PERF_LOG_SAMPLE_INTERVAL_SEC ENGINE_PROFILE_SAMPLE_EVERY_FRAME
#elif ENGINE_PROFILE_LEVEL >= ENGINE_PROFILE_LEVEL_BASIC
#define ENGINE_PROFILE_TIMING_SAMPLE_INTERVAL_SEC 1.0f
#define ENGINE_PROFILE_PROCESS_MEMORY_SAMPLE_INTERVAL_SEC 1.0f
#define ENGINE_PROFILE_RESOURCE_MEMORY_SAMPLE_INTERVAL_SEC 1.0f
#define ENGINE_RUNTIME_PERF_LOG_SAMPLE_INTERVAL_SEC 1.0f
#else
#define ENGINE_PROFILE_TIMING_SAMPLE_INTERVAL_SEC 0.0f
#define ENGINE_PROFILE_PROCESS_MEMORY_SAMPLE_INTERVAL_SEC 0.0f
#define ENGINE_PROFILE_RESOURCE_MEMORY_SAMPLE_INTERVAL_SEC 0.0f
#define ENGINE_RUNTIME_PERF_LOG_SAMPLE_INTERVAL_SEC 0.0f
#endif
